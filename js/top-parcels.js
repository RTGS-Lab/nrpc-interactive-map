// Top parcels table: the highest-ranked parcels in Hennepin County, a city, or a watershed district.
// A section of the right-side container (js/side-panel.js); the selected parcel is shown by the
// "Parcel" section (js/parcel-card.js).
//
// Asks (Bryan, 2026-11-12): "create a table option to see the top parcels for the county and then
// by each jurisdiction layer provided in the clip and zip. On select in the table, it should select
// the parcel on the map and provide a 'zoom to' option"; "it should play nice with the 'zoom to'
// tool as well"; "a right side popout ... an option to collapse it or expand it".
//
// Data: data/top-parcels.json, generated by 06-output-20261112-make-protected-data.py (task dir
// 2026-W46 THU 01) and fetched the first time the table opens (nothing extra at page load). Ranks
// are the re-rank without already-protected and MSP Airport parcels (js/protected-v1.js). A parcel
// belongs to the city / watershed district that holds its centre. Up to top_n rows per area.
//
// One state with the Zoom to tool: the tool's checkboxes are the area selection.
// - Zoom to -> table: ticking areas (or Clear) re-scopes the table; no map movement.
// - Table -> Zoom to: picking an area in the table ticks it in Zoom to (its outline, Clip & Zip
//   extent and, on branch city-mask, its grey mask) and frames it with the Zoom button's own code.
//   Picking Hennepin County clears the Zoom to selection and does not move the map.
// - Round 6 (Bryan, 2026-11-12): a row click / Enter / Space only highlights its parcel (the one
//   map highlight + a short pulse; no card, no collapse, no map movement); arrows move the
//   highlight. One panel-level button, "Zoom to selected", acts on the highlighted row: it zooms
//   with the Zoom to tool's code and opens the Parcel card, and the list stays visible. It is
//   disabled ("Select a row first") until a row is highlighted, names its target, and says
//   "off screen" when the parcel is outside the view. Shortcut: Z or Ctrl+Enter in the list.
//   Only the user collapses the list. A row's Zoom to uses window.NRPCZoomTo.zoomToExtent,
//   the Zoom to tool's own zoom; the container's view padding keeps the parcel beside it.
// - The selected row follows the card (a map click on a listed parcel marks its row; closing the
//   card clears it); a scope change that drops the selected parcel closes the card.

window.NRPCTopParcels = (() => {
  const PAGE = 50;
  const MIN_PARCEL_EXTENT_M = 500;   // a tiny lot is framed in at least 500 m of context
  const fmt = n => n.toLocaleString("en-US");
  let view, model, side, sec, card, data = null, loading = null;
  let scope = { kind: "county" };    // {kind: county} | {kind: city|watershed|mixed, items: [..]}
  let shown = PAGE, rows = [], selectedPid = null, driving = false;
  let btn, kindSel, areaSel, scopeNote, thead, tbody, moreBtn, countLine, statusLine, zoomBtn, offHint;

  // ── Zoom to tool (its own DOM: #city-checkbox-scroll, #city-zoom-btn, #city-clear-btn) ──────
  const zt = {
    scroll: () => document.getElementById("city-checkbox-scroll"),
    checked() {
      const s = this.scroll();
      if (!s) return { kind: "county" };
      if (s.querySelector("#city-cb-full-county:checked")) return { kind: "county", full: true };
      const boxes = [...s.querySelectorAll("input[data-type]:checked")];
      if (!boxes.length) return { kind: "county" };
      const kinds = [...new Set(boxes.map(b => b.dataset.type))];
      return { kind: kinds.length === 1 ? kinds[0] : "mixed",
               items: boxes.map(b => ({ kind: b.dataset.type, name: b.value })) };
    },
    box(kind, name) {
      return [...(this.scroll() || document).querySelectorAll(`input[data-type='${kind}']`)]
        .find(b => b.value === name);
    },
    select(kind, name) {               // tick one area, the way a click in the list would
      driving = true;
      try {
        document.getElementById("city-clear-btn")?.click();
        if (kind === "county") return true;
        const b = this.box(kind, name);
        if (!b) return false;
        b.checked = true;
        b.dispatchEvent(new Event("change", { bubbles: true }));
        document.getElementById("city-zoom-btn")?.click();   // the tool's own framing
        return true;
      } finally { driving = false; }
    },
  };

  function scopeFromZoomTo() {
    const c = zt.checked();
    if (c.kind === "county") return { kind: "county" };
    return { kind: c.kind, items: c.items };
  }

  // ── rows for a scope ────────────────────────────────────────────────────────────────────
  function rowsFor(s) {
    const S = data.scopes;
    if (s.kind === "county") return S.county.map(i => data.rows[i]);
    const seen = new Set(), out = [];
    s.items.forEach(it => (S[it.kind][it.name] || []).forEach(i => {
      if (!seen.has(i)) { seen.add(i); out.push(data.rows[i]); }
    }));
    return out.sort((a, b) => a[1] - b[1] || (a[0] < b[0] ? -1 : 1));
  }

  function scopeLabel(s) {
    if (s.kind === "county") return "Hennepin County";
    const nm = it => it.kind === "watershed" ? titleCase(it.name) : it.name;
    return s.items.length === 1 ? nm(s.items[0]) : `${s.items.length} areas: ${s.items.map(nm).join(", ")}`;
  }
  const titleCase = str => str.toLowerCase().replace(/\b\w/g, c => c.toUpperCase());

  // ── render ──────────────────────────────────────────────────────────────────────────────
  function syncPickers() {
    const single = scope.kind !== "county" && scope.items.length === 1 ? scope.items[0] : null;
    if (scope.kind === "county") kindSel.value = "county";
    else if (single) kindSel.value = single.kind;
    else kindSel.value = "zoomto";
    kindSel.querySelector("option[value=zoomto]").hidden = !(scope.kind !== "county" && !single);
    fillAreas(kindSel.value, single ? single.name : null);
  }

  function fillAreas(kind, selectedName) {
    areaSel.innerHTML = "";
    const list = kind === "city" ? data.cities : kind === "watershed" ? data.watersheds : [];
    areaSel.disabled = !list.length;
    areaSel.hidden = !list.length;
    if (!list.length) return;
    const ph = document.createElement("option");
    ph.value = ""; ph.textContent = kind === "city" ? "Choose a city..." : "Choose a district...";
    areaSel.appendChild(ph);
    list.forEach(n => {
      const o = document.createElement("option");
      o.value = n; o.textContent = kind === "watershed" ? titleCase(n) : n;
      areaSel.appendChild(o);
    });
    areaSel.value = selectedName || "";
  }

  // Columns by scope (UI review, finding 5): "#" only where it differs from Rank; City only where
  // the scope is not one city; class as a swatch with its name as a tooltip; Address wraps.
  function columns() {
    const oneCity = scope.kind === "city" && scope.items.length === 1;
    const cols = [];
    if (scope.kind !== "county") cols.push({ k: "pos", h: "#", t: "Position in this area", num: true });
    cols.push({ k: "rank", h: "Rank", t: `Rank among ${fmt(data.parcels_ranked)} ranked parcels`, num: true });
    cols.push({ k: "cls", h: "Class", t: "Class (legend v1.0)" });
    cols.push({ k: "pid", h: "PID", t: "Parcel ID" });
    cols.push({ k: "addr", h: "Address", t: "Street address" });
    if (!oneCity) cols.push({ k: "city", h: "City", t: "City", hide: "phone" });
    cols.push({ k: "acres", h: "Acres", t: "Acres", num: true, hide: "phone" });
    cols.push({ k: "score", h: "Score", t: "Overall score (0-100)", num: true });
    return cols;
  }

  function render() {
    rows = rowsFor(scope);
    sec.setSummary(scopeLabel(scope));
    scopeNote.textContent = `Top parcels in ${scopeLabel(scope)}`;
    statusLine.textContent = `Rank = rank among ${fmt(data.parcels_ranked)} ranked parcels. ` +
      `Already-protected (${fmt(data.excluded.protected)}) and MSP Airport ` +
      `(${fmt(data.excluded.msp)}) parcels are not ranked or listed. A parcel belongs to the city ` +
      `or district that holds its centre.`;
    const cols = columns();
    thead.innerHTML = "<tr>" + cols.map(c => `<th scope="col" title="${c.t}" class="${c.num ? "tp-num" : ""}` +
      `${c.hide ? " tp-hide-" + c.hide : ""}">${c.h}</th>`).join("") + "</tr>";
    tbody.innerHTML = "";
    const n = Math.min(shown, rows.length);
    rows.slice(0, n).forEach((r, i) => tbody.appendChild(rowEl(r, i + 1, cols)));
    countLine.textContent = `Showing ${fmt(n)} of ${fmt(rows.length)}` +
      (rows.length >= data.top_n && scope.kind !== "mixed" && (scope.items || []).length <= 1
        ? ` (each area lists its top ${fmt(data.top_n)})` : "");
    moreBtn.hidden = n >= rows.length;
    markSelected();
    fitRows();
  }

  // With the card open below, the list is sized to show its first 6 rows (rows that wrap are
  // taller, so measured rather than fixed). Without the card the list takes the panel.
  function fitRows(n = 6) {
    const wrap = sec && sec.body.querySelector(".tp-wrap");
    if (!wrap) return;
    if (!side.el.classList.contains("sp-both")) { wrap.style.height = ""; return; }
    const trs = [...tbody.querySelectorAll("tr")].slice(0, n);
    const h = thead.getBoundingClientRect().height + trs.reduce((t, r) => t + r.getBoundingClientRect().height, 0);
    if (h > 0) wrap.style.height = `${Math.ceil(h + 2)}px`;
  }

  function rowEl(r, pos, cols) {
    const [pid, rank, cls, acres, ov, city, ws, addr] = r;
    const tr = document.createElement("tr");
    tr.tabIndex = 0;
    tr.dataset.pid = pid;
    tr.setAttribute("aria-selected", "false");
    const c = window.NRPCModelV1.CLASSES[cls];
    const val = {
      pos: fmt(pos), rank: fmt(rank), pid, addr: addr || "", city: data.cities[city] || "",
      acres: acres.toFixed(2), score: ov.toFixed(1),
    };
    cols.forEach(col => {
      const td = document.createElement("td");
      if (col.k === "cls") {
        td.innerHTML = `<span class="tp-swatch" style="background:${c.color}" title="${data.class_labels[cls]}"></span>` +
          `<span class="tp-sr">${data.class_labels[cls]}</span>`;
      } else td.textContent = val[col.k];
      if (col.k === "score") td.title = ov.toFixed(4);
      td.className = [col.num ? "tp-num" : "", col.k === "addr" ? "tp-addr" : "", col.k === "pid" ? "tp-pid" : "",
                      col.k === "city" ? "tp-city" : "",
                      col.hide ? "tp-hide-" + col.hide : ""].filter(Boolean).join(" ");
      tr.appendChild(td);
    });
    tr.addEventListener("click", () => highlightRow(pid));
    tr.addEventListener("keydown", e => {
      if ((e.key === "Enter" && (e.ctrlKey || e.metaKey)) || e.key === "z" || e.key === "Z") {
        e.preventDefault(); if (selectedPid !== pid) highlightRow(pid); zoomSelected(); return;
      }
      if (e.key === "Enter" || e.key === " ") { e.preventDefault(); highlightRow(pid); }
      if (e.key === "ArrowDown" || e.key === "ArrowUp") {
        e.preventDefault();
        const n = nextRow(tr, e.key === "ArrowDown" ? 1 : -1);
        if (n) { n.focus(); highlightRow(n.dataset.pid); }
      }
    });
    return tr;
  }
  function nextRow(tr, d) {
    let n = d > 0 ? tr.nextElementSibling : tr.previousElementSibling;
    while (n && n.classList.contains("tp-actions")) n = d > 0 ? n.nextElementSibling : n.previousElementSibling;
    return n;
  }

  function markSelected() {
    if (!tbody) return;
    tbody.querySelectorAll("tr").forEach(tr => {
      const on = tr.dataset.pid === selectedPid;
      tr.classList.toggle("tp-selected", on);
      tr.setAttribute("aria-selected", on ? "true" : "false");
    });
    updateZoomButton();
  }

  // The one "Zoom to selected" button: disabled until a row is highlighted; names its target.
  let offscreen = false;
  function updateZoomButton() {
    if (!zoomBtn) return;
    const r = selectedPid && data ? data.rows.find(x => x[0] === selectedPid) : null;
    const name = r && r[7] ? r[7] : selectedPid;
    zoomBtn.disabled = !selectedPid;
    zoomBtn.textContent = selectedPid ? `Zoom to ${name}` : "Zoom to selected";
    zoomBtn.title = selectedPid ? `Zoom to parcel ${selectedPid} and open its card (Z or Ctrl+Enter in the list)`
                                : "Select a row first";
    offHint.hidden = !(selectedPid && offscreen);
  }

  // ── select / zoom: the card does the selection; the Zoom to tool's zoom does the framing ──
  async function highlightRow(pid) {
    selectedPid = pid; markSelected();
    const res = await card.mark(pid);
    if (res && card.markedPid === pid) { offscreen = res.offscreen; updateZoomButton(); }
  }

  async function zoomSelected() {
    if (!selectedPid) return;
    const pid = selectedPid;
    const f = await card.select(pid, { focus: false });       // opens the card; list stays
    if (!f) return;
    await card.zoomTo();
    offscreen = false; updateZoomButton();
  }
  const selectParcel = (pid, zoom) => zoom ? highlightRow(pid).then(zoomSelected) : highlightRow(pid);

  // A scope change closes the card only when its parcel lies outside the new area (centroid
  // tested against the Zoom to tool's own layers); a parcel that is in the area but below its
  // top 500 keeps its card.
  let scopeSeq = 0;
  async function dropStaleSelection() {
    const my = ++scopeSeq;
    const pid = selectedPid, f = card.feature;
    if (!pid || !f || scope.kind === "county" || rows.some(r => r[0] === pid)) return;
    const c = f.geometry.centroid || f.geometry.extent.center;
    const layerFor = k => k === "city"
      ? view.map.allLayers.find(l => l.type === "feature" && l.title && l.title.toLowerCase().includes("cities"))
      : view.map.allLayers.find(l => l.title === "Watershed Districts");
    let inside = false;
    for (const it of scope.items) {
      const lyr = layerFor(it.kind);
      if (!lyr) { inside = true; break; }              // cannot tell: keep the card
      const q = lyr.createQuery();
      q.geometry = c; q.spatialRelationship = "intersects";
      q.where = `${it.kind === "city" ? "CTU_NAME" : "BWSR_NAME"} = '${it.name.replace(/'/g, "''")}'`;
      try { if (await lyr.queryFeatureCount(q) > 0) { inside = true; break; } }
      catch (e) { inside = true; break; }
    }
    if (my === scopeSeq && !inside && card.pid === pid) card.clear();
  }

  function setScope(s) {
    scope = s; shown = PAGE;
    if (!data) return;
    syncPickers(); render(); dropStaleSelection();
  }

  // ── CSV of the rows shown ────────────────────────────────────────────────────────────────
  function csv() {
    const head = ["rank_in_scope", "rank_ranked_parcels", "class", "PID", "address", "city",
                  "watershed_district", "acres", "overall_value", "published_rank"];
    const q = v => /[",\n]/.test(String(v)) ? `"${String(v).replace(/"/g, '""')}"` : String(v);
    const lines = [head.join(",")];
    rows.slice(0, Math.min(shown, rows.length)).forEach((r, i) => {
      lines.push([i + 1, r[1], data.class_labels[r[2]], r[0], r[7], data.cities[r[5]] || "",
                  data.watersheds[r[6]] || "", r[3], r[4], r[8]].map(q).join(","));
    });
    const blob = new Blob([lines.join("\n") + "\n"], { type: "text/csv" });
    const a = document.createElement("a");
    a.href = URL.createObjectURL(blob);
    a.download = `top-parcels-${scopeLabel(scope).replace(/[^A-Za-z0-9]+/g, "-").toLowerCase()}.csv`;
    a.click();
    setTimeout(() => URL.revokeObjectURL(a.href), 1000);
  }

  // ── section body ─────────────────────────────────────────────────────────────────────────
  function buildBody(el) {
    el.classList.add("tp-body");
    el.innerHTML = `
      <div class="tp-pickers">
        <label class="tp-sr" for="tp-kind">Area type</label>
        <select id="tp-kind">
          <option value="county">Hennepin County</option>
          <option value="city">City</option>
          <option value="watershed">Watershed District</option>
          <option value="zoomto" hidden>Zoom to selection</option>
        </select>
        <label class="tp-sr" for="tp-area">Area</label>
        <select id="tp-area" hidden></select>
      </div>
      <div class="tp-scope" aria-live="polite"></div>
      <div class="tp-actionbar">
        <button type="button" class="tp-zoomsel" disabled title="Select a row first">Zoom to selected</button>
        <span class="tp-offscreen" hidden>off screen</span>
      </div>
      <div class="tp-wrap" data-keep-scroll>
        <table>
          <thead></thead>
          <tbody></tbody>
        </table>
      </div>
      <div class="tp-foot">
        <span class="tp-count"></span>
        <button type="button" class="tp-more">Show 50 more</button>
        <button type="button" class="tp-csv">Download CSV</button>
      </div>
      <div class="tp-status"></div>`;
    kindSel = el.querySelector("#tp-kind");
    areaSel = el.querySelector("#tp-area");
    scopeNote = el.querySelector(".tp-scope");
    tbody = el.querySelector("tbody");
    thead = el.querySelector("thead");
    zoomBtn = el.querySelector(".tp-zoomsel");
    offHint = el.querySelector(".tp-offscreen");
    zoomBtn.addEventListener("click", () => zoomSelected());
    moreBtn = el.querySelector(".tp-more");
    countLine = el.querySelector(".tp-count");
    statusLine = el.querySelector(".tp-status");

    kindSel.addEventListener("change", () => {
      const k = kindSel.value;
      if (k === "county") { zt.select("county"); setScope({ kind: "county" }); return; }
      if (k === "zoomto") { setScope(scopeFromZoomTo()); return; }
      fillAreas(k, null);
      areaSel.focus();
    });
    areaSel.addEventListener("change", () => {
      const k = kindSel.value, name = areaSel.value;
      if (!name) return;
      zt.select(k, name);
      setScope({ kind: k, items: [{ kind: k, name }] });
    });
    moreBtn.addEventListener("click", () => { shown += PAGE; render(); });
    el.querySelector(".tp-csv").addEventListener("click", csv);
  }

  async function load() {
    if (data) return data;
    if (!loading) {
      statusLine.textContent = "Loading...";
      loading = fetch("data/top-parcels.json").then(r => r.json());
    }
    data = await loading;
    return data;
  }

  async function onShow() {
    btn.classList.add("active");
    btn.setAttribute("aria-expanded", "true");
    await load();
    card.turnModelOn();
    setScope(scopeFromZoomTo());
    if (!sec.expanded) sec.expand(true);
    kindSel.focus();
  }
  function onHide() {
    btn.classList.remove("active");
    btn.setAttribute("aria-expanded", "false");
    btn.focus();
  }

  function init(v, m, afterBtn, sidePanel, parcelCard) {
    view = v; model = m; side = sidePanel; card = parcelCard;
    if (!model || !model.layer || !window.NRPCProtectedV1 || !side || !card) return null;
    btn = document.createElement("button");
    btn.id = "top-parcels-toggle";
    btn.className = "panel-toggle";
    btn.textContent = "Top parcels";
    btn.setAttribute("aria-controls", "sp-top");
    btn.setAttribute("aria-expanded", "false");
    afterBtn.after(btn);
    sec = side.section("top", "Top parcels", 1);
    if (side.wideButton) sec.addHeadButton(side.wideButton);    // Wider lives in this header
    buildBody(sec.body);
    sec.onShow = onShow;
    sec.onHide = onHide;
    btn.addEventListener("click", () => sec.show(!sec.visible));

    // Zoom to -> table (user ticks, Full County, Clear); the table's own drive is ignored
    document.addEventListener("change", e => {
      if (driving || !e.target.closest || !e.target.closest("#city-checkbox-scroll")) return;
      setScope(scopeFromZoomTo());
    });
    document.addEventListener("click", e => {
      if (driving || !e.target.closest || !e.target.closest("#city-clear-btn")) return;
      setScope({ kind: "county" });
    });
    // the selected row follows the card
    card.onChange(pid => { if (pid !== selectedPid) { selectedPid = pid; offscreen = false; } markSelected(); });
    new MutationObserver(() => requestAnimationFrame(() => fitRows()))
      .observe(side.el, { attributes: true, attributeFilter: ["class"] });
    window.addEventListener("resize", () => fitRows());
    view.watch("stationary", st => {
      if (!st || !selectedPid || card.markedPid !== selectedPid) return;
      const f = card.markedFeature;
      if (f) { offscreen = card.isOffscreen(f); updateZoomButton(); }
    });
    const api = { show: v2 => sec.show(v2 ?? !sec.visible), section: sec, setScope, selectParcel,
                  highlightRow, zoomSelected, get offscreen() { return offscreen; },
                  get rows() { return rows; }, get selectedPid() { return selectedPid; },
                  get scope() { return scope; } };
    if (window.__nrpc) window.__nrpc.top = api;     // ?debug only
    return api;
  }

  return { init };
})();
