// Parcels that are not ranked: already protected, and the MSP airport. Greyed on the map, left out
// of the model's ranking, explained in the legend.
//
// Asks (Bryan, 2026-11-12): "grey out the already protected areas and do the ranking step without
// them included"; "mask MSP out" (the airport); "In the legend, add a note about what the
// classification breaks are." Already protected = the NRPC model explorer's rule (Kristine Maurer
// via Bryan, 2026-11-10): >= 50% of the parcel's area in the V2 protected set. MSP = every parcel
// the county parcel layer codes MUNIC_NM 'MET AIRPORT'. Data: js/protected-v1-data.js,
// data/protected-parcels.geojson, data/msp-parcels.geojson, all generated by
// 06-output-20261112-make-protected-data.py (task dir 2026-W46 THU 01); no numbers typed here.
//
// Everything happens in the browser; the web map and its services are not changed. The renderer
// still reads the published Rank (all 445,517 parcels). Removing parcels does not change the order
// of the rest, so the seven classes over the ranked parcels are exact as Rank thresholds, and a
// parcel's rank = Rank minus the number of excluded parcels with a smaller Rank. Both were checked
// parcel by parcel against a direct re-rank when the data file was built.
//
// Exposes window.NRPCProtected: apply(view, deps, model), decorateLegend(wrapper), rankOf(),
// classRanges(), LABEL, MSP_LABEL.

window.NRPCProtected = (() => {
  const D = window.NRPCProtectedV1;
  const LABEL = "Already protected -- not ranked";
  const MSP_LABEL = "MSP Airport -- not ranked";
  // CIM colours in the JS API are [r, g, b, alpha 0-255]
  const GREY_FILL = [217, 217, 217, 255];  // #D9D9D9, opaque: hides the class colour underneath
  const GREY_LINE = [128, 128, 128, 255];  // #808080: the city mask's grey (branch city-mask)
  const MSP_FILL = [166, 166, 166, 255];   // #A6A6A6: same grey family, one step darker
  const MSP_LINE = [96, 96, 96, 255];      // #606060
  const fmt = n => n.toLocaleString("en-US");

  // Rank among the ranked parcels (0 = not ranked), from the published Rank.
  const excludedSet = D ? new Set([...D.pids, ...D.msp_pids]) : new Set();
  function rankOf(pid, publishedRank) {
    if (excludedSet.has(pid)) return 0;
    const pr = D.excluded_ranks;
    let lo = 0, hi = pr.length;
    while (lo < hi) { const mid = (lo + hi) >> 1; if (pr[mid] < publishedRank) lo = mid + 1; else hi = mid; }
    return publishedRank - lo;
  }

  // Class ranges in rank among ranked parcels, straight from the generated breaks.
  function classRanges() {
    const n = D.parcels_ranked;
    let lo = 1, prevPct = 0;
    return window.NRPCModelV1.CLASSES.map((c, i) => {
      const hi = D.breaks_ranked[i];
      const r = { name: c.label.split(" -- ")[0], lo, hi, fromPct: prevPct, toPct: 100 * hi / n };
      lo = hi + 1; prevPct = r.toPct;
      return r;
    });
  }

  // Classes from model-v1.js (labels and colours kept), breaks moved to the ranked parcels.
  function classBreakInfos(classes) {
    const outline = { color: [40, 40, 40, 0.35], width: 0.4 };
    let min = 0.5;
    return classes.map((c, i) => {
      const max = D.thresholds_published_rank[i] + 0.5;
      const info = { minValue: min, maxValue: max, label: c.label,
                     symbol: { type: "simple-fill", color: c.color, outline } };
      min = max;
      return info;
    });
  }

  const stroke = (color, width) => ({ type: "CIMSolidStroke", enable: true, width, color });
  const hatch = (color, rotation, separation) => ({
    type: "CIMHatchFill", enable: true, rotation, separation,
    lineSymbol: { type: "CIMLineSymbol", symbolLayers: [stroke(color, 0.6)] } });
  const cim = layers => ({ type: "cim", data: { type: "CIMSymbolReference",
                                                symbol: { type: "CIMPolygonSymbol", symbolLayers: layers } } });

  // Already protected: light grey + #808080 diagonal hatch (the explorer's "hatched, not ranked").
  const protectedSymbol = () => cim([stroke(GREY_LINE, 0.6), hatch(GREY_LINE, 45, 5),
                                     { type: "CIMSolidFill", enable: true, color: GREY_FILL }]);
  // MSP airport: darker grey + cross-hatch, so it reads apart from "already protected".
  const mspSymbol = () => cim([stroke(MSP_LINE, 0.8), hatch(MSP_LINE, 45, 6), hatch(MSP_LINE, -45, 6),
                               { type: "CIMSolidFill", enable: true, color: MSP_FILL }]);

  // Popup for the model layer: rank among the ranked parcels, or why it is not ranked.
  function popupTemplate() {
    const status = `
      var prot = ${JSON.stringify(D.pids)};
      var msp = ${JSON.stringify(D.msp_pids)};
      var pr = ${JSON.stringify(D.excluded_ranks)};
      var r = $feature.Rank;
      if (Includes(prot, $feature.PID)) { return "${LABEL}"; }
      if (Includes(msp, $feature.PID)) { return "${MSP_LABEL}"; }
      var lo = 0; var hi = Count(pr);
      while (lo < hi) { var mid = Floor((lo + hi) / 2); if (pr[mid] < r) { lo = mid + 1; } else { hi = mid; } }
      return Text(r - lo, "#,###") + " of ${fmt(D.parcels_ranked)} ranked parcels";`;
    return {
      title: "Parcel {PID}",
      outFields: ["PID", "Rank", "Overall_Va"],
      expressionInfos: [{ name: "rank_ranked", title: "Rank among ranked parcels", expression: status }],
      content: [{
        type: "fields",
        fieldInfos: [
          { fieldName: "expression/rank_ranked", label: "Rank among ranked parcels" },
          { fieldName: "Rank", label: "Published rank, all parcels (v1.0)",
            format: { digitSeparator: true, places: 0 } },
          { fieldName: "Overall_Va", label: "Overall Value", format: { digitSeparator: false, places: 4 } },
        ],
      }],
    };
  }

  function overlay(GeoJSONLayer, url, title, symbol, minScale) {
    const l = new GeoJSONLayer({
      url, title, popupEnabled: false,   // the model layer's popup says why it is not ranked
      legendEnabled: false, listMode: "hide", minScale, maxScale: 0,
      renderer: { type: "simple", symbol },
    });
    l.nrpcHelper = true;                 // not offered by Clip & Zip
    return l;
  }

  function apply(view, deps, model) {
    if (!D || !model || !model.layer) { console.warn("protected: data or model layer missing"); return null; }
    const { GeoJSONLayer } = deps;
    const layer = model.layer;
    const r = layer.renderer.clone();
    r.classBreakInfos = classBreakInfos(window.NRPCModelV1.CLASSES);
    layer.renderer = r;
    layer.outFields = ["PID", "Rank", "Overall_Va"];
    layer.popupTemplate = popupTemplate();

    const prot = overlay(GeoJSONLayer, "data/protected-parcels.geojson", "Already protected",
                         protectedSymbol(), layer.minScale);
    const msp = overlay(GeoJSONLayer, "data/msp-parcels.geojson", "MSP Airport",
                        mspSymbol(), layer.minScale);
    if (model.group) model.group.addMany([prot, msp]);            // top of the model group
    else view.map.addMany([prot, msp], view.map.layers.indexOf(layer) + 1);
    return { overlay: prot, msp };
  }

  // Legend: two "not ranked" rows under the seven classes, what is ranked, and a collapsible
  // "How classes are set" with each class's rank range and share (from the generated breaks).
  function decorateLegend(wrapper) {
    const box = wrapper.querySelector("#model-legend");
    if (!box || !D) return;
    const ramp = box.querySelector(".ml-ramp");
    const row = (cls, label) => {
      const el = document.createElement("div");
      el.className = `ml-row ${cls}`;
      el.innerHTML = `<span class="ml-swatch"></span><span class="ml-label"></span>`;
      el.querySelector(".ml-label").textContent = label;
      return el;
    };
    const protRow = row("ml-protected", LABEL);
    const mspRow = row("ml-protected ml-msp", MSP_LABEL);
    const scope = document.createElement("div");
    scope.className = "ml-note ml-scope";
    scope.textContent = `${fmt(D.parcels_ranked)} parcels ranked; already-protected ` +
      `(${fmt(D.parcels_protected)}) and MSP Airport (${fmt(D.parcels_msp)}) parcels are not ranked.`;

    const how = document.createElement("details");
    how.className = "ml-how";
    const sum = document.createElement("summary");
    sum.textContent = "How classes are set";
    const p1 = document.createElement("div");
    p1.className = "ml-how-text";
    p1.textContent = "Each class is a range of rank (1 = highest Overall Value) among the " +
      `${fmt(D.parcels_ranked)} ranked parcels, cut at the top 1, 5, 10, 25, 50 and 75%.`;
    const list = document.createElement("ul");
    list.className = "ml-how-list";
    const pct = x => `${x.toFixed(1)}%`;
    classRanges().forEach((c, i, all) => {
      const li = document.createElement("li");
      const share = i === 0 ? `top ${pct(c.toPct)}`
        : i === all.length - 1 ? `bottom ${pct(100 - c.fromPct)}`
        : `${pct(c.fromPct)} to ${pct(c.toPct)}`;
      li.textContent = `${c.name}: ranks ${fmt(c.lo)} to ${fmt(c.hi)} (${share})`;
      list.appendChild(li);
    });
    how.append(sum, p1, list);
    ramp.after(protRow);
    protRow.after(mspRow);
    mspRow.after(scope);
    scope.after(how);
  }

  return { apply, decorateLegend, rankOf, classRanges, LABEL, MSP_LABEL };
})();
