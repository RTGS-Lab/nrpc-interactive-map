// Parcel scorecard: a parcel click (or a Top parcels row) opens the "Parcel" section of the
// right-side container (js/side-panel.js) instead of the map popup.
//
// Ask (Bryan, 2026-11-12): "On a parcel click, instead of a popup table, have a panel open on the
// right and a parcel scorecard be added." Built from section 3 of the parcel report card spec
// (2026-W46/2026-11-10T0639-TUESDAY/11-nrpc-map-parcel-report-card-spec-SUBAGENT/04-output-...),
// updated: the legend v1.0 classes, this branch's re-rank, MSP airport, no owner fields ever.
//
// Data, and only what it supports:
// - Live model layer (AGOL FeatureServer/96, queried by PID on select): PID, Rank, Overall_Va and
//   the six category scores -> overall, rank, class and the six category bars + the sum check.
// - data/card-v1-run.json (fetched on the first select): category labels and weights, county
//   median / 90th percentile of each category's points over ranked parcels, the 16 inputs with
//   their source lines, the rank rule text.
// - data/card-v1/<PID[:5]>.json.gz (fetched per select, about 11 kB): the inputs' values and
//   points from the explorer's v1 replay -> "why this score" and the inputs under each category.
//   If a shard cannot be read, the card says "Inputs not published for this run".
// - County parcel layer (gis.hennepin.us, read-only): street address and city. Owner fields are
//   never requested.
// Generated by 45-output-20261112-make-card-data.py (task dir 2026-W46 THU 01); no numbers typed.
//
// Behaviour: one highlight (this module's, on the model layer view); a map click opens and expands
// Parcel and collapses (does not close) Top parcels to its header; a row click updates the card
// and leaves the table where it is; focus moves to the card heading; the close button hides the
// card and clears the highlight.
//
// inputs argument of renderCard: undefined = loading, null = not published / unreadable, object.
// Exposes window.NRPCParcelCard.init(view, model, side) -> { select(pid, opts), clear(),
// onChange(fn), turnModelOn(), pid }.

window.NRPCParcelCard = (() => {
  const P = window.NRPCProtected, D = window.NRPCProtectedV1;
  const COUNTY_PARCELS = "https://gis.hennepin.us/arcgis/rest/services/Maps/NATURALRESOURCES/MapServer/2";
  const fmt = n => n.toLocaleString("en-US");
  const esc = s => String(s ?? "").replace(/[&<>"]/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));
  let view, model, side, sec, el, run = null, runLoading = null;
  const shards = new Map();
  let current = null, marked = null, highlight = null, seq = 0, pulseLayer = null, lastPulse = 0;
  const listeners = [];

  function turnModelOn() {
    let l = model.layer;
    while (l && l !== view.map) { if (l.visible === false) l.visible = true; l = l.parent; }
  }

  // The run manifest plus the source-link audit (round 7, Bryan: "if you don't have the source
  // back to the full layer, do not add a source link"): data/card-v1-links.json, written by
  // 96-working-20261112-source-link-audit.py, maps each source URL on file to {verdict, name,
  // link}; only "full" entries become links, everything else is plain text.
  async function loadRun() {
    if (run) return run;
    runLoading = runLoading || Promise.all([
      fetch("data/card-v1-run.json").then(r => r.json()),
      fetch("data/card-v1-links.json").then(r => r.ok ? r.json() : {}).catch(() => ({})),
    ]).then(([m, links]) => { m.links = links; return m; });
    run = await runLoading;
    return run;
  }

  // A source's text and its full-layer links (round 7 rule), shared by the card and the export.
  function sourceParts(s, links) {
    const clean = t => String(t ?? "").replace(/\[NEEDS CONFIRM\]/g, "(not confirmed)");
    const full = String(s.url || "").split(/;\s*/).map(p => (p.match(/https?:\/\/\S+/) || [])[0])
      .filter(Boolean).map(u => links[u]).filter(v => v && v.verdict === "full" && v.link);
    return { text: `${clean(s.label)} -- ${clean(s.agency)}; ${clean(s.date)}`,
             links: full.map(v => ({ name: v.name, href: v.link })) };
  }

  // One source line: "label -- agency; date", then links to the full layers it names, if any.
  function sourceLine(s, links) {
    const full = String(s.url || "").split(/;\s*/).map(p => (p.match(/https?:\/\/\S+/) || [])[0])
      .filter(Boolean).map(u => links[u]).filter(v => v && v.verdict === "full" && v.link);
    const a = full.map(v => `<a href="${esc(v.link)}" target="_blank" rel="noopener">${esc(v.name)}</a>`);
    const clean = t => String(t ?? "").replace(/\[NEEDS CONFIRM\]/g, "(not confirmed)");   // internal marker
    return `<li class="pc-src">${esc(clean(s.label))} -- ${esc(clean(s.agency))}; ${esc(clean(s.date))}` +
      (a.length ? `. Source layer${a.length > 1 ? "s" : ""}: ${a.join(", ")}` : "") + `</li>`;
  }

  async function loadShard(pid) {
    const pre = pid.slice(0, 5);
    if (!shards.has(pre)) {
      shards.set(pre, (async () => {
        const r = await fetch(`data/card-v1/${pre}.json.gz`);
        if (!r.ok) throw new Error(`shard ${pre}: ${r.status}`);
        const buf = new Uint8Array(await r.arrayBuffer());
        let text;
        if (buf[0] === 0x1f && buf[1] === 0x8b) {          // raw gzip bytes (GitHub Pages, http.server)
          const s = new Blob([buf]).stream().pipeThrough(new DecompressionStream("gzip"));
          text = await new Response(s).text();
        } else {                                            // a server already decoded it
          text = new TextDecoder().decode(buf);
        }
        return JSON.parse(text);
      })());
    }
    const sh = await shards.get(pre);
    const rec = sh.p[pid];
    if (!rec) return null;
    const n = sh.f.length;
    const out = {};
    sh.f.forEach((f, i) => { out[f] = { value: rec[i], points: rec[n + i] }; });
    return out;
  }

  async function address(pid) {
    try {
      const u = `${COUNTY_PARCELS}/query?` + new URLSearchParams({
        where: `PID='${pid.replace(/'/g, "''")}'`, outFields: "HOUSE_NO,STREET_NM,MUNIC_NM,ZIP_CD",
        returnGeometry: "false", f: "json" });
      const a = (await (await fetch(u)).json()).features?.[0]?.attributes;
      if (!a) return "";
      let st = (a.STREET_NM || "").trim();
      let hn = a.HOUSE_NO || 0;
      if (/ADDRESS UNASSIGNED/i.test(st)) { st = ""; hn = 0; }
      const city = (a.MUNIC_NM || "").trim().replace(/\b\w+/g, w => w[0] + w.slice(1).toLowerCase());
      return [hn ? `${hn} ${st}` : st, city].filter(Boolean).join(", ");
    } catch (e) { return ""; }
  }

  // ── select ───────────────────────────────────────────────────────────────────────────────
  async function queryParcel(pid) {
    const q = model.layer.createQuery();
    q.where = `PID = '${pid.replace(/'/g, "''")}'`;
    q.outFields = ["*"];
    q.returnGeometry = true;
    q.outSpatialReference = view.spatialReference;
    return (await model.layer.queryFeatures(q)).features[0] || null;
  }

  // Mark a parcel (Bryan, 2026-11-12, round 6: a table row click "highlight[s] its location"):
  // the one highlight plus a short cyan pulse; no card, no collapse, no map movement. If the card
  // is already open it follows the mark in place (no focus move), so the map and the card never
  // show two different parcels. Returns {feature, offscreen}.
  async function mark(pid) {
    const my = ++seq;
    turnModelOn();
    const f = await queryParcel(pid);
    if (my !== seq) return null;
    marked = { pid, feature: f };
    setHighlight(f);
    if (f) pulse(f);
    listeners.forEach(fn => fn(pid));
    if (sec.visible) select(pid, { open: false, focus: false, mine: my });
    return { feature: f, offscreen: f ? isOffscreen(f) : false };
  }

  function isOffscreen(f) {
    return !(view.extent && f && f.geometry && view.extent.intersects(f.geometry.extent));
  }

  // A cyan outline that narrows and fades over about 1.4 s, drawn above everything.
  function pulse(f) {
    if (!pulseLayer) return;
    pulseLayer.removeAll();
    const g = new pulseLayer.GraphicCtor({ geometry: f.geometry,
      symbol: { type: "simple-fill", color: [0, 194, 255, 0.18], outline: { color: [0, 194, 255, 1], width: 7 } } });
    pulseLayer.add(g);
    const t0 = performance.now(), D = 1400;
    lastPulse = Date.now();
    const step = t => {
      const k = Math.min(1, (t - t0) / D);
      if (!pulseLayer.graphics.includes(g)) return;
      g.symbol = { type: "simple-fill", color: [0, 194, 255, 0.18 * (1 - k)],
                   outline: { color: [0, 194, 255, 1 - 0.85 * k], width: 7 - 5 * k } };
      if (k < 1) requestAnimationFrame(step); else pulseLayer.remove(g);
    };
    requestAnimationFrame(step);
  }

  // Open (or update) the card. opts.open false: update an open card in place; opts.focus false:
  // keep the focus where it is. Never collapses the Top parcels list (round 6).
  async function select(pid, opts = {}) {
    const my = opts.mine || ++seq;
    turnModelOn();
    const [f, r] = await Promise.all([marked && marked.pid === pid && marked.feature ? marked.feature : queryParcel(pid), loadRun()]);
    if (my !== seq) return null;                       // a newer selection won
    current = { pid, feature: f };
    marked = { pid, feature: f };
    if (opts.open !== false) { sec.show(true); if (!sec.expanded) sec.expand(true); }
    setHighlight(f);
    renderCard(pid, f, r, undefined, "");          // inputs loading
    if (f && window.NRPCMetc) window.NRPCMetc.summary(pid, f.geometry).then(() => refreshMetc(pid)).catch(() => {});
    listeners.forEach(fn => fn(pid));
    if (opts.focus !== false) focusHeading();
    const [inputs, addr] = await Promise.all([f ? loadShard(pid).catch(() => null) : null, address(pid)]);
    if (my !== seq) return f;
    const hadFocus = el.contains(document.activeElement);
    renderCard(pid, f, r, inputs, addr);
    if (hadFocus && opts.focus !== false) focusHeading();   // the re-render replaced the content
    return f;
  }

  // The section header is the card's one heading (UI review, finding 12).
  function focusHeading() { sec.focusHeader(); }

  // Zoom to the selected parcel with the Zoom to tool's own zoom; a lot is framed in >= 500 m.
  async function zoomTo() {
    const f = (current && current.feature) || (marked && marked.feature);
    if (!f) return;
    if (side.mode === "wide") side.setMode("open");
    let e = f.geometry.extent.clone();
    const grow = 500 / Math.max(e.width, e.height, 1);
    if (grow > 1) e = e.expand(grow);
    if (side.isPhone()) side.setMode("collapsed");              // show the map, keep the strip
    await window.NRPCZoomTo.zoomToExtent(e, window.NRPCZoomTo.AREA_FACTOR);
  }

  async function setHighlight(f) {
    if (highlight) { highlight.remove(); highlight = null; }
    if (!f) return;
    const lv = await view.whenLayerView(model.layer);
    if (marked && marked.feature === f) { if (highlight) highlight.remove(); highlight = lv.highlight(f); }
  }

  function clear() {
    seq++;
    if (highlight) { highlight.remove(); highlight = null; }
    current = null; marked = null;
    if (pulseLayer) pulseLayer.removeAll();
    if (sec.visible) sec.show(false);
    listeners.forEach(fn => fn(null));
  }

  // ── Metropolitan Council layers (Bryan, 2026-11-12: "METC checkboxes in the parcel report that
  // shows in the app"): a read-only checklist from js/metc-layers.js, the same list, order and
  // words as the export; the indicator is an image, not an input, so it cannot look editable.
  function metcRowsHtml(pid) {
    const M = window.NRPCMetc;
    const rows = M.cached(pid);
    return M.LAYERS.map((l, i) => {
      const r = rows && rows[i];
      const state = !r ? "pending" : r.error ? "error" : r.count ? "yes" : "no";
      const aria = state === "yes" ? "Included" : state === "no" ? "Not included" : state === "error" ? "Could not check" : "Checking";
      const val = !r ? "checking Met Council layers..." : M.valueText(r);
      return `<li class="pc-metc-row pc-metc-${state}"><span class="pc-check" role="img" aria-label="${aria}"></span>` +
             `<span class="pc-metc-name">${esc(l.label)}</span><span class="pc-metc-val">${esc(val)}</span></li>`;
    }).join("");
  }
  function metcBlock(pid) {
    if (!window.NRPCMetc) return "";
    return `<details class="pc-metc" open><summary>Metropolitan Council layers</summary>
      <ul class="pc-metc-list">${metcRowsHtml(pid)}</ul></details>`;
  }
  function refreshMetc(pid) {
    const ul = el.querySelector(".pc-metc-list");
    if (ul && current && current.pid === pid) ul.innerHTML = metcRowsHtml(pid);
  }

  // ── render ───────────────────────────────────────────────────────────────────────────────
  // "(top 0.9%)"; nothing for the top 0.1%, where the rank says it plainly (finding 11)
  function topPct(rank) {
    const x = 100 * rank / D.parcels_ranked;
    return x < 0.1 ? "" : ` (top ${x.toFixed(x >= 10 ? 0 : 1)}%)`;
  }

  function renderCard(pid, f, r, inputs, addr) {
    sec.setSummary(pid);
    if (!f) {
      el.innerHTML = `<p class="pc-status">Parcel ${esc(pid)}: not in this model run.</p>`;
      return;
    }
    const a = f.attributes;
    const overall = a.Overall_Va;
    const rank = P.rankOf(pid, a.Rank);
    const isProt = D.pids.includes(pid), isMsp = D.msp_pids.includes(pid);
    const ranges = P.classRanges();
    const cls = rank ? ranges.findIndex(c => rank <= c.hi) : -1;
    const C = window.NRPCModelV1.CLASSES;

    let rankHtml;
    if (isProt) rankHtml = `<p class="pc-rank"><strong>Already protected: scored, not ranked.</strong></p>
        <p class="pc-rule">${esc(r.rank.protected_rule)}</p>`;
    else if (isMsp) rankHtml = `<p class="pc-rank"><strong>MSP Airport: not ranked</strong></p>
        <p class="pc-rule">${esc(r.rank.msp_rule)}</p>`;
    else rankHtml = `<p class="pc-rank">Rank <strong>${fmt(rank)}</strong> of ${fmt(D.parcels_ranked)}
        ranked parcels${topPct(rank)}</p>
        <p class="pc-class"><span class="pc-swatch" style="background:${C[cls].color}"></span>${esc(C[cls].label)}</p>`;

    // bars: earned = 100 x weight x category score (live layer); possible = 100 x weight
    const cats = r.categories.map(c => {
      const score = Number(a[c.field]) || 0;
      return { ...c, earned: 100 * c.weight * score, possible: 100 * c.weight };
    });
    const sum = cats.reduce((t, c) => t + c.earned, 0);
    const sumOk = Math.abs(sum - overall) <= 0.001;
    const byCat = {};
    r.inputs.forEach(i => { (byCat[i.category] = byCat[i.category] || []).push(i); });

    const barRows = cats.map(c => {
      const pct = x => `${Math.max(0, Math.min(100, 100 * x / c.possible)).toFixed(2)}%`;
      const ins = byCat[c.key] || [];
      const inputsHtml = inputs ? `<details class="pc-inputs"><summary>Inputs (${ins.length})</summary><ul>` +
        ins.map(i => {
          const v = inputs[i.field] || {};
          const src = (i.sources || []).map(s => sourceLine(s, r.links || {})).join("");
          return `<li><span class="pc-in-label">${esc(i.label)}</span>: value read ${esc(v.value ?? "[not on file]")},
            ${v.points == null ? "[not on file]" : v.points.toFixed(2)} points, within-category weight
            ${Math.round(100 * i.within)}%${src ? `<ul class="pc-srcs">${src}</ul>` : ""}</li>`;
        }).join("") + `</ul></details>` : "";
      return `<tr>
          <th scope="row">${esc(c.label)} <span class="pc-w">${Math.round(100 * c.weight)}%</span></th>
          <td class="pc-barcell"><div class="pc-bar" aria-hidden="true">
              <div class="pc-fill" style="width:${pct(c.earned)}"></div>
              <div class="pc-mark pc-p50" style="left:${pct(c.county.p50)}" title="County median ${c.county.p50.toFixed(1)}"></div>
              <div class="pc-mark pc-p90" style="left:${pct(c.county.p90)}" title="90th percentile ${c.county.p90.toFixed(1)}"></div></div></td>
          <td class="pc-num">${c.earned.toFixed(1)} of ${c.possible.toFixed(0)}<span class="tp-sr">; county median
            ${c.county.p50.toFixed(1)}, 90th percentile ${c.county.p90.toFixed(1)}</span></td>
        </tr>
        ${inputsHtml ? `<tr class="pc-sub"><td colspan="3">${inputsHtml}</td></tr>` : ""}`;
    }).join("");

    // why this score: template from the numbers on the card
    const top2 = [...cats].sort((x, y) => y.earned - x.earned).slice(0, 2);
    const gap = [...cats].sort((x, y) => (y.possible - y.earned) - (x.possible - x.earned))[0];
    const why = [`Most points come from ${top2.map(c => `${c.label} (${c.earned.toFixed(1)} of ${c.possible.toFixed(0)})`).join(" and ")}.`];
    if (inputs) {
      const tops = r.inputs.map(i => ({ ...i, ...(inputs[i.field] || {}) }))
        .filter(i => (i.points || 0) > 0).sort((x, y) => y.points - x.points).slice(0, 3);
      why.push(tops.length
        ? `The inputs adding the most: ${tops.map(i => `${i.label} (value ${i.value}, ${i.points.toFixed(1)} points)`).join("; ")}.`
        : "No input adds points to this parcel.");
    }
    why.push(`Largest gap: ${gap.label}, ${gap.earned.toFixed(1)} of ${gap.possible.toFixed(0)} points.`);

    // What the card shows, for the export (js/parcel-export.js): same numbers, same words.
    if (current && current.pid === pid) current.print = {
      pid, addr, runLabel: r.label, overall, rank: rank || null, rankedCount: D.parcels_ranked,
      status: isProt ? "protected" : isMsp ? "msp" : "ranked",
      rankLine: isProt ? "Already protected: scored, not ranked." : isMsp ? "MSP Airport: not ranked"
        : `Rank ${fmt(rank)} of ${fmt(D.parcels_ranked)} ranked parcels${topPct(rank)}`,
      rule: isProt ? r.rank.protected_rule : isMsp ? r.rank.msp_rule : null,
      cls: rank ? { label: C[cls].label, color: C[cls].color } : null,
      sumOk, sum,
      cats: cats.map(c => ({ key: c.key, label: c.label, weight: c.weight, earned: c.earned, possible: c.possible,
                             p50: c.county.p50, p90: c.county.p90 })),
      why: why.slice(),
      inputs: inputs ? r.inputs.map(i => ({ category: i.category, label: i.label, within: i.within,
        value: (inputs[i.field] || {}).value, points: (inputs[i.field] || {}).points,
        sources: (i.sources || []).map(sv => sourceParts(sv, r.links || {})) })) : null,
      published: a.Rank, acres: a.Shape__Area ? a.Shape__Area / 4046.8564224 : null,
    };
    // the numbers on the card, for the checks (?debug)
    if (current && current.pid === pid) current.numbers = {
      pid, overall, rank: rank || null, protected: isProt, msp: isMsp, sumOk, sum,
      cats: Object.fromEntries(cats.map(c => [c.key, c.earned])),
      inputs: inputs ? Object.fromEntries(Object.entries(inputs)) : inputs };
    const acres = a.Shape__Area ? a.Shape__Area / 4046.8564224 : null;
    const notRanked = isProt ? "Already protected -- not ranked" : isMsp ? "MSP Airport -- not ranked" : null;
    el.innerHTML = `
      <div class="pc-head">
        <p class="pc-addr">${addr ? esc(addr) : "&nbsp;"}</p>
        <button type="button" class="pc-zoom">Zoom to</button>
      </div>
      <p class="pc-run">${esc(r.label)}</p>
      <p class="pc-score"><span class="pc-big">${overall.toFixed(1)}</span> of 100 overall score</p>
      ${rankHtml}
      <h4>Category points</h4>
      ${sumOk ? `<table class="pc-bars"><caption class="tp-sr">Points earned of points possible, by category</caption>
        <tbody>${barRows}</tbody></table>
        <p class="pc-legend">Tick marks: <span class="pc-key pc-key-50"></span>county median and
          <span class="pc-key pc-key-90"></span>90th percentile of ranked parcels.</p>`
        : `<p class="pc-status">Data mismatch: the categories add up to ${sum.toFixed(4)}, the overall score is
          ${overall.toFixed(4)}. Bars hidden.</p>`}
      <h4>Why this score</h4>
      <ul class="pc-why">${why.map(s => `<li>${esc(s)}</li>`).join("")}</ul>
      ${inputs === null ? `<p class="pc-status">Inputs not published for this run.</p>`
        : inputs === undefined ? `<p class="pc-status">Loading inputs...</p>` : ""}
      ${metcBlock(pid)}
      <details class="pc-record"><summary>Parcel record</summary>
        <table class="pc-facts"><tbody>
          <tr><th scope="row">PID</th><td>${esc(pid)}</td></tr>
          <tr><th scope="row">Rank among ranked parcels</th><td>${rank ? `${fmt(rank)} of ${fmt(D.parcels_ranked)}` : esc(notRanked)}</td></tr>
          <tr><th scope="row">Published rank, all parcels (v1.0)</th><td>${fmt(a.Rank)}</td></tr>
          <tr><th scope="row">Overall Value</th><td>${overall.toFixed(4)}</td></tr>
          ${acres ? `<tr><th scope="row">Area</th><td>${acres.toFixed(2)} acres</td></tr>` : ""}
        </tbody></table>
        <p class="pc-note">The published rank counts all ${fmt(D.parcels_total)} parcels; the rank above
          leaves out already-protected and MSP Airport parcels.</p>
        ${sumOk ? `<p class="pc-note">Check: the six category points add up to the overall score
          (${overall.toFixed(4)}).</p>` : ""}</details>`;
    el.querySelector(".pc-zoom")?.addEventListener("click", () => zoomTo());
  }

  function init(v, m, s, deps = {}) {
    view = v; model = m; side = s;
    if (deps.GraphicsLayer && deps.Graphic) {
      pulseLayer = new deps.GraphicsLayer({ title: "Parcel pulse", listMode: "hide" });
      pulseLayer.nrpcHelper = true;
      pulseLayer.GraphicCtor = deps.Graphic;
      view.map.add(pulseLayer);
    }
    if (!model || !model.layer || !P || !D || !side) return null;
    sec = side.section("parcel", "Parcel", 2);
    el = document.createElement("div");
    el.className = "pc-card";
    sec.body.appendChild(el);
    sec.onHide = () => { if (current) clear(); };

    // the map popup no longer opens for the model layer; a click selects through the card
    model.layer.popupEnabled = false;
    view.on("click", async e => {
      const hit = await view.hitTest(e, { include: [model.layer] });
      const g = hit.results.find(x => x.graphic && x.graphic.layer === model.layer);
      if (g && g.graphic.attributes && g.graphic.attributes.PID) select(g.graphic.attributes.PID, { from: "map" });
    });
    const api = { select, mark, clear, zoomTo, turnModelOn, isOffscreen, onChange: fn => listeners.push(fn),
                  get markedPid() { return marked && marked.pid; }, get lastPulse() { return lastPulse; },
                  get markedFeature() { return marked && marked.feature; },
                  get pid() { return current && current.pid; },
                  get feature() { return current && current.feature; },
                  get print() { return current && current.print; },
                  get metc() { return current && window.NRPCMetc ? window.NRPCMetc.cached(current.pid) : null; },
                  get numbers() { return current && current.numbers; }, section: sec };
    if (window.__nrpc) window.__nrpc.card = api;
    return api;
  }

  return { init };
})();
